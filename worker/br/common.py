class BRException(Exception):
    """Base class for all expected (non-crash) failures."""

    exit_code = 1

    def __init__(self, message: str, *, exit_code: int | None = None):
        super().__init__(message)
        if exit_code is not None:
            self.exit_code = exit_code


class ValidationError(BRException):
    exit_code = 2


class IntegrityError(BRException):
    exit_code = 3


class PreflightError(BRException):
    exit_code = 4


class HelperError(BRException):
    exit_code = 5


class Interrupted(BRException):
    exit_code = 130


