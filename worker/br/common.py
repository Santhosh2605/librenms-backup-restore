SECRET_KEYS = re.compile(
    r"(password|passwd|secret|token|key|identity|passphrase|APP_KEY|authorization)",
    re.IGNORECASE,
)


def redact(value: str, limit: int = 400) -> str:
    """Best-effort secret scrubber for log lines."""
    value = SECRET_KEYS.sub("***", value)
    return value[:limit]


class Logger:
    """Line-oriented logger that writes one JSON object per line.

    The GUI tails these files, so a stable schema matters more than
    human prettiness.  ``stream`` may also be a list (used by tests).
    """

    def __init__(self, path: str | None = None, *, echo: bool = False):
        self.path = path
        self.echo = echo
        self._fh = None
        self._buffer: list[str] | None = None
        if path:
            os.makedirs(os.path.dirname(path), exist_ok=True)
            self._fh = open(path, "a", encoding="utf-8", buffering=1)

    def capture(self) -> None:
        """Redirect to an in-memory buffer (tests)."""
        self._buffer = []

    def lines(self) -> list[str]:
        return list(self._buffer or [])

    def log(self, severity_level: str, text: str, **fields: t.Any) -> None:
        """Append one structured record.

        Parameters are named ``severity_level``/``text`` (not ``level``/
        ``message``) so that call sites may freely pass ``level=`` or
        ``message=`` as structured fields without a name collision.
        """
        if self._buffer is not None:
            self._buffer.append(f"{severity_level} {text} {fields}")
            return
        record = {"ts": utc_now(), "level": severity_level, "message": redact(str(text))}
        if fields:
            record["fields"] = {k: redact(str(v)) for k, v in fields.items()}
        line = json.dumps(record, separators=(",", ":"))
        if self._fh:
            self._fh.write(line + "\n")
        if self.echo:
            # Echo goes to stderr, never stdout: inside br-helper, stdout is the
            # line-delimited HMAC response channel. Anything written there
            # corrupts the protocol for the caller.
            print(line, file=sys.stderr, flush=True)

    def info(self, message: str, **f: t.Any) -> None:
        self.log("info", message, **f)

    def warn(self, message: str, **f: t.Any) -> None:
        self.log("warning", message, **f)

    def error(self, message: str, **f: t.Any) -> None:
        self.log("error", message, **f)

    def progress(self, percent: int, stage: str, message: str = "") -> None:
        self.log("progress", message or stage,
                 percent=max(0, min(100, int(percent))), progress_stage=stage)

    def close(self) -> None:
        if self._fh:
            self._fh.close()
            self._fh = None


def utc_now() -> str:
    from datetime import datetime, timezone

    return datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")


