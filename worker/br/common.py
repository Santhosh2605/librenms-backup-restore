def sha256_file(path: str, chunk: int = CHUNK) -> str:
    digest = hashlib.sha256()
    with open(path, "rb") as fh:
        for block in iter(lambda: fh.read(chunk), b""):
            digest.update(block)
    return digest.hexdigest()


def sha256_stream(read, write=None) -> str:
    """Hash a stream, optionally tee-ing it to ``write``."""
    digest = hashlib.sha256()
    for block in iter(lambda: read(CHUNK), b""):
        digest.update(block)
        if write:
            write(block)
    return digest.hexdigest()


def du_bytes(path: str) -> int:
    total = 0
    for root, _dirs, files in os.walk(path):
        for name in files:
            try:
                total += os.lstat(os.path.join(root, name)).st_size
            except OSError:
                continue
    return total


def free_bytes(path: str) -> int:
    stat = os.statvfs(path)
    return stat.f_bavail * stat.f_frsize


def human(size: float) -> str:
    for unit in ("B", "KiB", "MiB", "GiB", "TiB"):
        if abs(size) < 1024 or unit == "TiB":
            return f"{size:.1f} {unit}" if unit != "B" else f"{int(size)} B"
        size /= 1024
    return f"{size:.1f} TiB"


def safe_join(root: str, *parts: str) -> str:
    """Join and guarantee the result stays inside ``root`` (no traversal)."""
    root_abs = os.path.abspath(root)
    candidate = os.path.abspath(os.path.join(root_abs, *parts))
    if candidate != root_abs and not candidate.startswith(root_abs + os.sep):
        raise ValidationError(f"path traversal blocked: {candidate!r} escapes {root_abs!r}")
    return candidate


def validate_abs_path(path: str, *, must_exist: bool = False) -> str:
    if not isinstance(path, str) or not path.startswith("/"):
        raise ValidationError(f"not an absolute path: {path!r}")
    if ".." in path.split(os.sep):
        raise ValidationError(f"path traversal blocked: {path!r}")
    if not SAFE_PATH_RE.match(path):
        raise ValidationError(f"path contains unsupported characters: {path!r}")
    if must_exist and not os.path.exists(path):
        raise ValidationError(f"path does not exist: {path!r}")
    return path


def load_json(path: str) -> t.Any:
    with open(path, "r", encoding="utf-8") as fh:
        return json.load(fh)


def load_json_typed(path: str, expected: type) -> t.Any:
    data = load_json(path)
    if not isinstance(data, expected):
        raise IntegrityError(
            f"{os.path.basename(path)}: expected {expected.__name__}, got {type(data).__name__}"
        )
    return data


def write_json(path: str, data: t.Any) -> None:
    tmp = f"{path}.tmp"
    with open(tmp, "w", encoding="utf-8") as fh:
        json.dump(data, fh, indent=2, sort_keys=True)
        fh.write("\n")
        fh.flush()
        os.fsync(fh.fileno())
    os.replace(tmp, path)


# ---------------------------------------------------------------------------
# Process execution - always argv lists, never a shell
# ---------------------------------------------------------------------------

def run(
    argv: list[str],
    *,
    cwd: str | None = None,
    env: dict[str, str] | None = None,
    timeout: int | None = None,
    check: bool = True,
    capture: bool = True,
    input_bytes: bytes | None = None,
) -> subprocess.CompletedProcess:
    """Run ``argv`` without a shell.

    ``shell=True`` is never used anywhere in this project: the first
    element is an absolute path validated by the caller.
    """
    if not argv or not os.path.isabs(argv[0]):
        raise ValidationError(f"argv[0] must be an absolute path, got {argv[:1]!r}")
    proc = subprocess.run(
        argv,
        cwd=cwd,
        env=env,
        timeout=timeout,
        check=False,
        stdout=subprocess.PIPE if capture else None,
        stderr=subprocess.PIPE if capture else None,
        input=input_bytes,
    )
    if check and proc.returncode != 0:
        err = (proc.stderr or b"").decode("utf-8", "replace")[:2000]
        raise BRException(
            f"command failed ({proc.returncode}): {os.path.basename(argv[0])} :: {redact(err)}",
            exit_code=6,
        )
    return proc


def which(name: str, candidates: tuple[str, ...] = ()) -> str:
    for candidate in candidates:
        if os.path.isfile(candidate) and os.access(candidate, os.X_OK):
            return candidate
    found = shutil.which(name)
    if not found:
        raise PreflightError(f"required executable not found: {name}")
    return found


def pgrep(pattern: str) -> bool:
    """Return True if a process matching ``pattern`` is running."""
    proc = subprocess.run(["/usr/bin/pgrep", "-f", pattern], check=False,
                          stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
    return proc.returncode == 0
